/**
 * Generates the Ed25519 snapshot signing key pair.
 *   pnpm keys:generate --out <directory outside the repo>
 * Writes <out>/snapshot-signing-key.pem (mode 600) and the public half to
 * packages/shared/src/snapshot-public-key.ts. Refuses to write the private key inside the repo.
 */
import { existsSync, mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, isAbsolute } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { generateSigningKeyPair } from '@cc-setup-agent/core';

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const { values } = parseArgs({ options: { out: { type: 'string' }, force: { type: 'boolean' } } });

if (!values.out) {
  console.error('Usage: pnpm keys:generate --out <directory outside the repo> [--force]');
  process.exit(1);
}
const outDir = resolve(values.out);
const rel = relative(repoRoot, outDir);
if (!rel.startsWith('..') && !isAbsolute(rel)) {
  console.error(
    'Refusing to write the private key inside the repository. Choose a directory outside it.',
  );
  process.exit(1);
}
const privatePath = join(outDir, 'snapshot-signing-key.pem');
if (existsSync(privatePath) && !values.force) {
  console.error(`${privatePath} already exists. Pass --force to replace it.`);
  process.exit(1);
}

const { privateKeyPem, publicKeyPem } = generateSigningKeyPair();
mkdirSync(outDir, { recursive: true, mode: 0o700 });
writeFileSync(privatePath, privateKeyPem, { mode: 0o600 });
writeFileSync(
  join(repoRoot, 'packages/shared/src/snapshot-public-key.ts'),
  `// Generated by \`pnpm keys:generate\`. Public half of the snapshot signing key.\nexport const SNAPSHOT_PUBLIC_KEY_PEM = ${JSON.stringify(publicKeyPem)};\n`,
);
console.log(`Private key written to ${privatePath}`);
console.log('Set SNAPSHOT_SIGNING_KEY_PATH to that path in .env.');
console.log('Public key written to packages/shared/src/snapshot-public-key.ts (commit it).');
